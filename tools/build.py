"""森羅物語：漁歌 build tool (rebuilt for 1.4.0).

The original tools/build.py + tools/data.py were not available, so this version keeps the data as
one JSON file per export in tools/data/ and writes scripts/data/generated.js from it.

  python tools/build.py extract   generated.js -> tools/data/*.json  (one-time bootstrap; overwrites data/)
  python tools/build.py build     tools/data/*.json -> generated.js
  python tools/build.py check     build in memory and fail if generated.js differs
  python tools/build.py pack      build, then zip both packs into ../Kaleidoscope_Fishing_Voyage_v<version>.mcaddon

Edit tools/data/*.json, never generated.js. GUIDEBOOK_JSON is stored as an object and written back as
the ASCII-only JSON string Cookery's guidebook API expects (script events carry it in chunks).
"""
import json, os, re, sys, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BP = os.path.join(ROOT, "Kaleidoscope Fishing Voyage [BP]")
RP = os.path.join(ROOT, "Kaleidoscope Fishing Voyage [RP]")
GEN = os.path.join(BP, "scripts", "data", "generated.js")
DATA = os.path.join(HERE, "data")
ORDER = os.path.join(DATA, "_order.json")   # [{"name", "ascii"}] keeps the export order and escaping
HEADER = "// AUTO-GENERATED by tools/build.py from tools/data/*.json. Do not edit by hand."
LINE = re.compile(r"^export const ([A-Z_]+) = (.*);$")
STRING_JSON = {"GUIDEBOOK_JSON"}             # exports whose value is a JSON document stored as a string


def dump(value, ascii_):
    return json.dumps(value, ensure_ascii=ascii_)


def extract():
    os.makedirs(DATA, exist_ok=True)
    order = []
    for line in open(GEN, encoding="utf-8").read().splitlines():
        m = LINE.match(line)
        if not m:
            continue
        name, raw = m.groups()
        value = json.loads(raw)
        ascii_ = dump(value, True) == raw
        if not ascii_ and dump(value, False) != raw:
            sys.exit(f"{name}: cannot reproduce its formatting")
        if name in STRING_JSON:
            doc = json.loads(value)
            if json.dumps(doc, ensure_ascii=True, separators=(",", ":")) != value:
                sys.exit(f"{name}: inner JSON is not in compact ASCII form")
            value = doc
        order.append({"name": name, "ascii": ascii_})
        with open(os.path.join(DATA, f"{name}.json"), "w", encoding="utf-8") as f:
            json.dump(value, f, ensure_ascii=False, indent=2)
            f.write("\n")
    with open(ORDER, "w", encoding="utf-8") as f:
        json.dump(order, f, indent=2)
        f.write("\n")
    print(f"extracted {len(order)} exports to {DATA}")


def render():
    out = [HEADER]
    for e in json.load(open(ORDER, encoding="utf-8")):
        value = json.load(open(os.path.join(DATA, f"{e['name']}.json"), encoding="utf-8"))
        if e["name"] in STRING_JSON:
            value = json.dumps(value, ensure_ascii=True, separators=(",", ":"))
        out.append(f"export const {e['name']} = {dump(value, e['ascii'])};")
    return "\n".join(out) + "\n"


def body(text):
    return [l for l in text.splitlines() if not l.startswith("//")]


def build():
    with open(GEN, "w", encoding="utf-8", newline="\n") as f:
        f.write(render())
    print(f"wrote {GEN}")


def check():
    if body(render()) != body(open(GEN, encoding="utf-8").read()):
        sys.exit("generated.js is out of date: run  python tools/build.py build")
    print("generated.js matches tools/data")


def version():
    return json.load(open(os.path.join(DATA, "ADDON_VERSION.json"), encoding="utf-8"))


def pack():
    build()
    v = version()
    for m in (os.path.join(BP, "manifest.json"), os.path.join(RP, "manifest.json")):
        mv = ".".join(map(str, json.load(open(m, encoding="utf-8"))["header"]["version"]))
        if mv != v:
            sys.exit(f"{m}: header version {mv} != ADDON_VERSION {v}")
    out = os.path.join(os.path.dirname(ROOT), f"Kaleidoscope_Fishing_Voyage_v{v}.mcaddon")
    n = 0
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for pack_dir in (BP, RP):
            for d, _, files in os.walk(pack_dir):
                for name in sorted(files):
                    p = os.path.join(d, name)
                    z.write(p, os.path.relpath(p, ROOT).replace(os.sep, "/"))
                    n += 1
    print(f"packed {n} files -> {out}")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    {"extract": extract, "build": build, "check": check, "pack": pack}[cmd]()
